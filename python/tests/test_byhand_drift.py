"""Drift guard: the generated by-hand pages must match their generator.

``docs/source/byhand4.rst`` and ``byhand5.rst`` are generated, not
hand-edited (see ``tools/gen_byhand.py``). This test fails if either file
drifts from the generator's current output -- catching a hand-edit, or a
generator change left unregenerated -- so the pytest gate keeps the pages
and the generator in sync.
"""

from __future__ import annotations

import importlib.util
from collections.abc import Callable
from pathlib import Path
from types import ModuleType
from typing import cast

import pytest

_REPO_ROOT: Path = Path(__file__).resolve().parents[2]
_GENERATOR: Path = _REPO_ROOT / "tools" / "gen_byhand.py"
_DOCS: Path = _REPO_ROOT / "docs" / "source"

# This is a BOOK-drift guard, not a hanoigame unit test: it reaches up to
# the repo root's `tools/` + `docs/`, which live beside the Python
# subproject, not inside it. When the Python subproject is built/tested in
# isolation (its image mounts only python/ at /hanoi-python), those sibling
# dirs are absent -- so skip rather than fail. The guard still runs from the
# full checkout: on the host, and in the root book gate (which has tools/ +
# docs/ present).
pytestmark = pytest.mark.skipif(
    not _GENERATOR.exists() or not _DOCS.exists(),
    reason=(
        "book-drift guard needs the repo root's tools/ + docs/ "
        "(present in the full checkout and the root book gate, "
        "absent in the isolated Python image)"
    ),
)


def _load_generator() -> ModuleType:
    """Import ``tools/gen_byhand.py`` by path (not an installed module)."""
    spec = importlib.util.spec_from_file_location("gen_byhand", _GENERATOR)
    assert spec is not None
    loader = spec.loader
    assert loader is not None
    module: ModuleType = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


@pytest.mark.parametrize("n", [4, 5])
def test_byhand_page_matches_generator(n: int) -> None:
    """``docs/source/byhandN.rst`` equals the generator's output (no drift)."""
    generator: ModuleType = _load_generator()
    page: Callable[[int], str] = cast(
        "Callable[[int], str]", vars(generator)["page"]
    )
    expected: str = page(n)
    actual: str = (_DOCS / f"byhand{n}.rst").read_text()
    assert actual == expected, (
        f"docs/source/byhand{n}.rst is out of sync with tools/gen_byhand.py; "
        f"regenerate with `python3 tools/gen_byhand.py`."
    )
